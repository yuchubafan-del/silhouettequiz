def init_database():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # 1. pokemons テーブル
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS pokemons (
        id INTEGER PRIMARY KEY,
        name_ja TEXT NOT NULL,
        name_en TEXT NOT NULL,
        type1 TEXT NOT NULL,
        type2 TEXT,
        genus TEXT,
        flavor_text TEXT,
        image_url TEXT NOT NULL,
        generation INTEGER DEFAULT 1
    );
    """)

    # 2. player_pokedex テーブル (図鑑・捕獲帳)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS player_pokedex (
        pokemon_id INTEGER PRIMARY KEY,
        captured_count INTEGER DEFAULT 0,
        first_captured_at DATETIME,
        last_captured_at DATETIME,
        FOREIGN KEY (pokemon_id) REFERENCES pokemons(id)
    );
    """)

    # 3. leaderboard テーブル (ランキング)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS leaderboard (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        player_name TEXT NOT NULL,
        score INTEGER NOT NULL,
        correct_count INTEGER NOT NULL,
        max_streak INTEGER NOT NULL,
        difficulty TEXT NOT NULL,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
    """)

    # 4. quiz_logs テーブル (1問ごとの回答ログ)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS quiz_logs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        pokemon_id INTEGER NOT NULL,
        chosen_name TEXT,
        is_correct INTEGER NOT NULL,
        hints_used INTEGER DEFAULT 0,
        time_taken_ms INTEGER DEFAULT 0,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (pokemon_id) REFERENCES pokemons(id)
    );
    """)

    # ポケモンデータの挿入 (REPLACE で更新可能)
    for p in POKEMON_DATA:
        p_id, name_ja, name_en, type1, type2, genus, flavor_text = p
        # 公式アートワーク画像URL (PokeAPIのGitHubホスト)
        image_url = f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/{p_id}.png"
        cursor.execute("""
            INSERT OR REPLACE INTO pokemons
            (id, name_ja, name_en, type1, type2, genus, flavor_text, image_url, generation)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1)
        """, (p_id, name_ja, name_en, type1, type2, genus, flavor_text, image_url))

    conn.commit()
    cursor.execute("SELECT count(*) FROM pokemons")
    total_count = cursor.fetchone()[0]
    conn.close()
    print(f"[OK] データベース初期化完了: {DB_PATH}")
    print(f"[OK] 登録ポケモン数: {total_count} 匹 (第1世代 151匹フルセット)")

if __name__ == "__main__":
    init_database()
